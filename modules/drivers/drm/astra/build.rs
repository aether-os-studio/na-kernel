//! `asic_reg` headers (register offsets and field shift/mask constants).
//!
//! The Linux source tree is located via the `LINUX_SRC_DIR` environment
//! variable (set by the GNUmakefile; defaults to `../../../../../../linux`
//! relative to this crate, i.e. the sibling of the naos tree).

